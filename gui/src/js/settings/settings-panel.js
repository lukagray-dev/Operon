/**
 * Builds a generic two-column settings row.
 *
 * @param {string} label       - Left-side label text.
 * @param {string} description - Left-side description text (may be empty).
 * @param {string} controlHtml - Right-side control HTML (button, select, toggle, etc.).
 * @returns {string} HTML for the row.
 */
function buildSettingRow(label, description, controlHtml) {
  return `
    <div class="settings-row">
      <div class="settings-row__info">
        <div class="settings-row__label">${escapeHtml(label)}</div>
        ${description ? `<div class="settings-row__description">${escapeHtml(description)}</div>` : ''}
      </div>
      <div class="settings-row__control">
        ${controlHtml}
      </div>
    </div>
  `;
}

