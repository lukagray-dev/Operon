/**
 * Renders an inline status indicator (used for loading or empty states).
 *
 * @param {string}  message  - Human-readable status text.
 * @param {boolean} [loading=false] - If true, shows an animated spinner.
 * @returns {string} HTML.
 */
function renderInlineStatus(message, loading = false) {
  const spinner = loading
    ? `<span class="model-selector__spinner" aria-hidden="true"></span>`
    : '';
  return `
    <div class="settings-inline-status">
      ${spinner}
      <span>${escapeHtml(message)}</span>
    </div>
  `;
}

/**
 * Escapes HTML special characters to prevent XSS when interpolating
 * untrusted strings into template literals.
 *
 * @param {string} raw - Untrusted input.
 * @returns {string} HTML-safe string.
 */
function escapeHtml(raw) {
  return String(raw ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

/**
 * Escapes a value for use inside an HTML attribute (e.g. data-*).
 * Replaces double-quotes so the attribute string remains valid.
 *
 * @param {string} raw - Input string.
 * @returns {string} Attribute-safe string.
 */
function escapeAttribute(raw) {
  return String(raw ?? '').replace(/"/g, '&quot;');
}

/**
 * Extracts a clean error message from an Error object, string, or unknown value.
 * Falls back to `fallback` when the error provides no useful message.
 *
 * @param {unknown} error    - Caught error of any type.
 * @param {string}  fallback - Shown when error.message is empty.
 * @returns {string}
 */
function normalizeErrorMessage(error, fallback = 'An unexpected error occurred.') {
  if (error instanceof Error && error.message) {
    return error.message;
  }
  if (typeof error === 'string' && error.trim()) {
    return error.trim();
  }
  return fallback;
}

