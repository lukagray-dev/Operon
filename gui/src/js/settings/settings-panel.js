// ── Module-Level State ───────────────────────────────────────────────────────

/**
 * The currently active settings category key.
 * Exported so that category modules can guard against stale renders
 * (e.g., "only render if activeCategory === 'models'").
 * @type {string}
 */
let activeCategory = 'models';

/**
 * Whether the settings dialog is currently open.
 * @type {boolean}
 */
let isOpen = false;

// ── Category Definitions ─────────────────────────────────────────────────────

// Each category key is mapped to its label and corresponding SVG filename located
// in the correct settings icons directory (gui/src/assets/icons/settings/).
const CATEGORIES = [
  { key: 'general',     label: 'General',     icon: 'category-general.svg' },
  { key: 'appearance',  label: 'Appearance',  icon: 'category-appearance.svg'    },
  { key: 'models',      label: 'Models',      icon: 'category-models.svg'      },
  { key: 'channels',    label: 'Channels',    icon: 'category-channels.svg'       },
  { key: 'permissions', label: 'Permissions', icon: 'category-permissions.svg'     },
  { key: 'skills',      label: 'Skills',      icon: 'category-skills.svg'     },
  { key: 'extensions',  label: 'Extensions',  icon: 'category-extensions.svg'        },
  { key: 'about',       label: 'About',       icon: 'category-about.svg'},
];

// ── DOM References ───────────────────────────────────────────────────────────

/** @type {HTMLElement|null} */
let overlayEl = null;

/** @type {HTMLElement|null} */
let mainEl = null;

// ── Initialization ───────────────────────────────────────────────────────────

/**
 * Creates the settings dialog element and appends it to <body>.
 * Should be called ONCE at application startup before openSettings().
 */
function initSettingsPanel() {
  // Guard: don't create a second overlay if already initialized
  if (document.getElementById('settings-overlay')) {
    return;
  }

  // Build the complete dialog HTML
  const overlayHtml = buildDialogHtml();

  // Inject into the end of <body>
  document.body.insertAdjacentHTML('beforeend', overlayHtml);

  // Cache DOM references
  overlayEl = document.getElementById('settings-overlay');
  mainEl = document.getElementById('settings-main');

  // Wire up the close button — ONLY the X button closes the dialog
  const closeBtn = document.getElementById('settings-close-btn');
  if (closeBtn) {
    closeBtn.addEventListener('click', closeSettings);
  }

  // Bind sidebar category click delegation
  const sidebar = document.getElementById('settings-sidebar');
  if (sidebar) {
    sidebar.addEventListener('click', handleSidebarClick);
  }

  // Apply saved appearance settings on startup
  applyAppearanceSettings();
}

// ── Dialog HTML Builder ──────────────────────────────────────────────────────

/**
 * Returns the complete HTML string for the settings overlay + dialog.
 * The sidebar nav is generated by buildLeftSidebar().
 * @returns {string}
 */
function buildDialogHtml() {
  return `
    <div class="settings-overlay" id="settings-overlay" role="dialog" aria-modal="true" aria-labelledby="settings-dialog-title">
      <div class="settings-dialog" id="settings-dialog">

        <!-- ── Header row (title + close button) ── -->
        <div class="settings-dialog__header">
          <h2 class="settings-dialog__title" id="settings-dialog-title">Settings</h2>
          <button
            class="settings-dialog__close"
            id="settings-close-btn"
            type="button"
            aria-label="Close settings"
            title="Close">
            ${buildCloseIconSvg()}
          </button>
        </div>

        <!-- ── Body (sidebar + main content) ── -->
        <div class="settings-dialog__body">

          <!-- Left navigation sidebar -->
          <nav class="settings-dialog__sidebar" id="settings-sidebar" aria-label="Settings categories">
            ${buildLeftSidebar(CATEGORIES, activeCategory)}
          </nav>

          <!-- Main content area — filled by renderCategoryPage() -->
          <main class="settings-dialog__main" id="settings-main" aria-live="polite">
          </main>

        </div>
      </div>
    </div>
  `;
}

/**
 * Returns an img tag pointing to the close (X) icon file.
 * The correct filename is close.svg and we load it relative to the index.html file
 * using './assets/icons/settings/close.svg'.
 * @returns {string}
 */
function buildCloseIconSvg() {
  return `<img src="./assets/icons/settings/close.svg" alt="Close" width="16" height="16" draggable="false">`;
}

// ── Open / Close ─────────────────────────────────────────────────────────────

/**
 * Opens the settings dialog.
 * Renders the last active category (or 'general' on first open).
 * @param {string} [category='general'] - Optional: jump directly to a category.
 */
function openSettings(category = activeCategory) {
  const disabledCategories = ['general', 'appearance', 'channels', 'skills', 'extensions', 'about'];
  if (disabledCategories.includes(category)) {
    category = 'models';
  }
  if (isOpen) {
    // If already open, just switch category if needed
    if (category !== activeCategory) {
      switchCategory(category);
    }
    return;
  }

  if (!overlayEl) {
    // Panel was never initialized — init now as a fallback
    initSettingsPanel();
  }

  isOpen = true;
  overlayEl.classList.add('is-open');

  // Lock body scroll while dialog is open
  document.body.style.overflow = 'hidden';

  // Render the current category
  switchCategory(category);
}

/**
 * Closes the settings dialog.
 * Resets transient async states in all category modules.
 */
function closeSettings() {
  if (!isOpen) return;

  isOpen = false;
  overlayEl.classList.remove('is-open');

  // Restore body scroll
  document.body.style.overflow = '';

  // Reset all transient loading/saving states so that re-opening
  // starts with a clean slate rather than stale spinners.
  resetAllCategoryStates();
}

/**
 * Resets transient module-level state across all category modules.
 * Called on dialog close.
 */
function resetAllCategoryStates() {
  resetAppearanceSettingsState();
  resetModelsSettingsState();
  resetChannelsSettingsState();
  resetPermissionsSettingsState();
  resetSkillsSettingsState();
  resetExtensionsSettingsState();
}

// ── Category Switching ───────────────────────────────────────────────────────

/**
 * Switches the main content area to the specified category.
 * Updates sidebar active highlight and re-renders the page.
 * @param {string} key - Category key (e.g. 'general', 'models').
 */
function switchCategory(key) {
  // Normalize the key — fall back to 'models' if unknown
  const resolved = CATEGORIES.find(c => c.key === key) ? key : 'models';
  activeCategory = resolved;

  // Update nav highlight
  const sidebar = document.getElementById('settings-sidebar');
  if (sidebar) {
    highlightNavItem(sidebar, resolved);
  }

  // Render the page for this category
  renderCategoryPage(resolved);
}

/**
 * Renders and hydrates the appropriate page into the main content area.
 * @param {string} category - Category key.
 */
async function renderCategoryPage(category) {
  if (!mainEl) return;

  // PLACEHOLDER: Default settings values for UI
  const settings = {
    launchAtStartup: false,
    enterBehavior: 'send',
    autoScroll: true,
    codeWrap: false,
    language: 'en',
  };

  // 1. Build static HTML for the page
  let html = '';
  switch (category) {
    case 'general':
      html = buildGeneralPage(settings);
      break;
    case 'appearance':
      html = buildAppearancePage(settings);
      break;
    case 'models':
      html = buildModelsPage();
      break;
    case 'channels':
      html = buildChannelsPage();
      break;
    case 'permissions':
      html = buildPermissionsPage();
      break;
    case 'skills':
      html = buildSkillsPage();
      break;
    case 'extensions':
      html = buildExtensionsPage();
      break;
    case 'about':
      html = buildAboutPageContent();
      break;
    default:
      html = buildGeneralPage(settings, state);
  }

  // 2. Inject HTML
  mainEl.innerHTML = html;

  // 3. Hydrate (bind events, trigger async data fetches)
  const dialog = document.getElementById('settings-dialog');
  switch (category) {
    case 'appearance':
      hydrateAppearancePage(mainEl);
      break;
    case 'models':
      await hydrateModelsPage(dialog);
      break;
    case 'channels':
      await hydrateChannelsPage(dialog);
      break;
    case 'permissions':
      await hydratePermissionsPage(dialog);
      break;
    case 'skills':
      await hydrateSkillsPage(dialog);
      break;
    case 'extensions':
      await hydrateExtensionsPage(dialog);
      break;
    case 'about':
      await hydrateAboutPage(mainEl);
      break;
    default:
      // general page needs no special hydration
      break;
  }

  // 4. Bind general-page save button if on general category
  if (category === 'general') {
    const saveBtn = mainEl.querySelector('#btn-check-updates');
    if (saveBtn) {
      saveBtn.addEventListener('click', () => {
        // Placeholder: trigger update check through IPC when available
        saveGeneralSettings();
      });
    }
  }
}

// ── Sidebar Delegation ───────────────────────────────────────────────────────

/**
 * Handles clicks inside the sidebar nav via event delegation.
 * Reads the data-category attribute from the clicked nav item.
 * @param {MouseEvent} event
 */
function handleSidebarClick(event) {
  const btn = /** @type {HTMLElement} */ (event.target).closest('[data-settings-category]');
  if (!btn) return;

  const key = btn.getAttribute('data-settings-category');
  if (key === 'general') {
    alert('General settings coming soon!');
    return;
  }
  if (key === 'appearance') {
    alert('Appearance settings coming soon!');
    return;
  }
  if (key === 'channels') {
    alert('Channels settings coming soon!');
    return;
  }
  if (key === 'skills') {
    alert('Skills settings coming soon!');
    return;
  }
  if (key === 'extensions') {
    alert('Extensions settings coming soon!');
    return;
  }
  if (key === 'about') {
    alert('About settings coming soon!');
    return;
  }
  if (key && key !== activeCategory) {
    switchCategory(key);
  }
}

