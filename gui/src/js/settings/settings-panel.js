/**
 * settings-panel.js
 *
 * Core orchestrator for the Settings popup dialog.
 *
 * Responsibilities:
 *  1. Build and inject the dialog HTML into the document.
 *  2. Open / close the dialog (only via the close button — not backdrop click).
 *  3. Track and switch between settings categories.
 *  4. Delegate page rendering and hydration to each category's JS module.
 *  5. Export shared utility helpers (buildSettingRow, escapeHtml, etc.)
 *     that category modules depend on.
 *
 * Dialog structure:
 *  .settings-overlay          <- full-screen backdrop
 *    .settings-dialog         <- 70vw × 70vh centered card
 *      .settings-dialog__header
 *        h2.settings-dialog__title
 *        button.settings-dialog__close
 *      .settings-dialog__body
 *        nav.settings-dialog__sidebar   <- left navigation
 *        main.settings-dialog__main     <- category page content
 */

